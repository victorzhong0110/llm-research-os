SOURCE_SHA256 = "6f608b71a7317216319b4d27b4d9bc84e6abd734eda7872b71a458569e2656c0"
CONFIG = {
    "dataset": "uci-iris-versicolor-virginica",
    "version": "v0alpha1",
    "split": "source-index-modulo-five-zero-heldout",
    "seed": 0,
    "trainingCount": 80,
    "heldoutCount": 20,
    "candidate": "nearest-class-centroid",
    "distance": "squared-euclidean-raw-four-features",
    "tieBreak": "class-zero",
    "baseline": "training-majority",
    "precision": "decimal-28",
}


def dataset() -> list[dict[str, Any]]:
    if hashlib.sha256(RAW.encode()).hexdigest() != SOURCE_SHA256:
        raise ValueError("the pinned dataset changed")
    rows = []
    for index, line in enumerate(RAW.splitlines()):
        if index < 50 or not line:
            continue
        fields = line.split(",")
        rows.append(
            {
                "id": f"uci-iris-{index + 1:03d}",
                "features": fields[:4],
                "label": 0 if fields[4] == "Iris-versicolor" else 1,
                "split": "held-out" if index % 5 == 0 else "train",
            }
        )
    return rows


def main() -> dict[str, Any]:
    rows = dataset()
    train = [row for row in rows if row["split"] == "train"]
    heldout = [row for row in rows if row["split"] == "held-out"]
    if len(train) != 80 or len(heldout) != 20:
        raise ValueError("unexpected fixed split")
    # No held-out labels participate in either fit. Local precision makes replay
    # independent of a caller's Decimal context. There is no random sampling.
    with localcontext() as context:
        context.prec = 28
        centers: list[list[Decimal]] = []
        for label in (0, 1):
            group = [row for row in train if row["label"] == label]
            centers.append(
                [
                    sum((Decimal(row["features"][axis]) for row in group), Decimal(0)) / len(group)
                    for axis in range(4)
                ]
            )
        majority = int(sum(row["label"] for row in train) * 2 > len(train))
        predictions = []
        for row in heldout:
            distances = [
                sum(
                    (Decimal(value) - center[axis]) ** 2
                    for axis, value in enumerate(row["features"])
                )
                for center in centers
            ]
            predictions.append(
                {
                    "exampleId": row["id"],
                    "baseline": majority,
                    "candidate": int(distances[1] < distances[0]),
                }
            )
    return {
        "kind": "IrisTrainingOutput",
        "version": "v0alpha1",
        "sourceSha256": SOURCE_SHA256,
        "config": dict(CONFIG),
        "training": train,
        "heldout": heldout,
        "models": {
            "baseline": {"majority": majority},
            "candidate": {"centroids": [[str(x) for x in c] for c in centers]},
        },
        "predictions": predictions,
    }
